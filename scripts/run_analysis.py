"""
Build the database, run every analysis query, and document the results.

    python scripts/run_analysis.py --setup     # create schema + seed data + functions, then analyse
    python scripts/run_analysis.py             # analyse an existing database

Connection settings come from the standard PostgreSQL environment variables
(PGHOST, PGPORT, PGUSER, PGPASSWORD, PGDATABASE); defaults match docker-compose.yml.

Outputs:
  docs/RESULTS.md        every business question, its SQL, and the result
  docs/figures/*.png     charts for the README
  exports/*.csv          tidy extracts for Power BI / Tableau
"""
from __future__ import annotations

import argparse
import os
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
import psycopg2

ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / "sql"
DOCS = ROOT / "docs"
FIG = DOCS / "figures"
EXPORTS = ROOT / "exports"

BLUE, RED, GREY, GREEN = "#2563eb", "#dc2626", "#9ca3af", "#059669"
plt.rcParams.update({"figure.dpi": 120, "axes.spines.top": False, "axes.spines.right": False, "font.size": 9})


def connect():
    return psycopg2.connect(
        host=os.getenv("PGHOST", "localhost"),
        port=os.getenv("PGPORT", "5432"),
        user=os.getenv("PGUSER", "postgres"),
        password=os.getenv("PGPASSWORD", "postgres"),
        dbname=os.getenv("PGDATABASE", "retail_demo"),
    )


def setup(con) -> None:
    for f in ["01_schema.sql", "02_seed_data.sql", "04_functions_and_views.sql"]:
        print(f"Running {f} ...")
        with con.cursor() as cur:
            cur.execute((SQL / f).read_text())
        con.commit()


def parse_queries(path: Path) -> list[dict]:
    text = path.read_text()
    blocks = re.split(r"^-- name:\s*", text, flags=re.M)[1:]
    out = []
    for b in blocks:
        name, rest = b.split("\n", 1)
        q = re.search(r"^-- question:\s*(.+)$", rest, flags=re.M)
        s = re.search(r"^-- skills:\s*(.+)$", rest, flags=re.M)
        sql = "\n".join(l for l in rest.splitlines() if not l.startswith("-- question:") and not l.startswith("-- skills:")).strip()
        out.append({"name": name.strip(), "question": q.group(1) if q else name,
                    "skills": s.group(1) if s else "", "sql": sql})
    return out


def run_queries(con) -> dict[str, pd.DataFrame]:
    results = {}
    with con.cursor() as cur:
        cur.execute("SET search_path TO retail")
        for q in parse_queries(SQL / "03_analysis_queries.sql"):
            cur.execute(q["sql"])
            cols = [d[0] for d in cur.description]
            df = pd.DataFrame(cur.fetchall(), columns=cols)
            for c in df.columns:  # Decimal -> float for charts/CSVs
                if df[c].map(lambda v: v.__class__.__name__ == "Decimal").any():
                    df[c] = df[c].astype(float)
            results[q["name"]] = df
            q["df"] = df
    return results


def md_table(df: pd.DataFrame, max_rows: int = 30) -> str:
    def fmt(v):
        if pd.isna(v):
            return ""
        if isinstance(v, float):
            return f"{v:,.0f}" if abs(v) >= 1000 else f"{v:,.2f}".rstrip("0").rstrip(".")
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)
    d = df.head(max_rows)
    lines = ["| " + " | ".join(d.columns) + " |", "|" + "---|" * len(d.columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in d.itertuples(index=False)]
    if len(df) > max_rows:
        lines.append(f"\n_…{len(df) - max_rows} more rows_")
    return "\n".join(lines)


def write_results_md() -> None:
    queries = parse_queries(SQL / "03_analysis_queries.sql")
    with connect() as con:
        res = run_queries(con)
    parts = ["# Query Results\n",
             "Generated by `scripts/run_analysis.py` against the seeded PostgreSQL database. "
             "Every result below is produced by the SQL shown with it.\n"]
    parts.append("## Contents\n" + "\n".join(
        f"{i}. [{q['question']}](#{q['name'].replace('_', '-')})" for i, q in enumerate(queries, 1)) + "\n")
    for q in queries:
        parts.append(f"<a id=\"{q['name'].replace('_', '-')}\"></a>\n## {q['question']}\n")
        if q["skills"]:
            parts.append(f"**SQL techniques:** {q['skills']}\n")
        parts.append(f"<details><summary>Show SQL</summary>\n\n```sql\n{q['sql']}\n```\n</details>\n")
        parts.append(md_table(res[q["name"]]) + "\n")
    (DOCS / "RESULTS.md").write_text("\n".join(parts))
    return res


def charts(res: dict[str, pd.DataFrame]) -> None:
    FIG.mkdir(parents=True, exist_ok=True)

    m = res["q01_monthly_revenue_growth"]
    fig, ax = plt.subplots(figsize=(9, 3.6))
    colors = [RED if mo[-2:] in ("11", "12") else BLUE for mo in m["month"]]
    ax.bar(m["month"], m["revenue"] / 1e6, color=colors)
    ax.set_ylabel("Revenue ($M)"); ax.set_title("Monthly revenue — holiday months in red")
    ax.tick_params(axis="x", rotation=60)
    fig.tight_layout(); fig.savefig(FIG / "monthly_revenue.png"); plt.close(fig)

    c = res["q03_category_performance"].sort_values("revenue_share_pct")
    fig, ax = plt.subplots(figsize=(7, 3.8))
    y = range(len(c))
    ax.barh([i + 0.2 for i in y], c["revenue_share_pct"], height=0.4, color=GREY, label="Share of revenue")
    ax.barh([i - 0.2 for i in y], c["profit_share_pct"], height=0.4, color=GREEN, label="Share of gross profit")
    ax.set_yticks(list(y)); ax.set_yticklabels(c["category_name"])
    ax.set_xlabel("%"); ax.set_title("Laptops lead revenue; Software leads profit"); ax.legend(frameon=False)
    fig.tight_layout(); fig.savefig(FIG / "category_revenue_vs_profit.png"); plt.close(fig)

    r = res["q07_rfm_segments"]
    fig, ax = plt.subplots(figsize=(7, 3.4))
    labels = r["segment"].str[3:]
    ax.bar(labels, r["customers"], color=GREY, label="Customers")
    ax2 = ax.twinx()
    ax2.plot(labels, r["revenue_share_pct"], color=BLUE, marker="o", label="Revenue share %")
    ax.set_ylabel("Customers"); ax2.set_ylabel("Revenue share (%)"); ax2.spines["top"].set_visible(False)
    ax.set_title("RFM segments: customers vs revenue share"); ax.tick_params(axis="x", rotation=20)
    fig.tight_layout(); fig.savefig(FIG / "rfm_segments.png"); plt.close(fig)

    rt = res["q10_returns_and_cancellations"].sort_values("return_rate_pct")
    fig, ax = plt.subplots(figsize=(6.5, 3.4))
    ax.barh(rt["category_name"], rt["return_rate_pct"],
            color=[RED if v == rt["return_rate_pct"].max() else GREY for v in rt["return_rate_pct"]])
    for i, v in enumerate(rt["return_rate_pct"]):
        ax.text(v, i, f" {v:.1f}%", va="center")
    ax.set_xlabel("Orders returned (%)"); ax.set_title("Return rate by category")
    fig.tight_layout(); fig.savefig(FIG / "return_rates.png"); plt.close(fig)


def exports() -> None:
    EXPORTS.mkdir(exist_ok=True)
    with connect() as con:
        for name, q in {
            "fact_sales": "SELECT * FROM retail.v_sales ORDER BY order_date, order_id, line_no",
            "customer_rfm": "SELECT * FROM retail.mv_customer_rfm ORDER BY customer_id",
            "dim_products": "SELECT p.*, c.category_name FROM retail.products p JOIN retail.categories c USING (category_id)",
            "dim_stores": "SELECT s.*, r.region_name FROM retail.stores s JOIN retail.regions r USING (region_id)",
        }.items():
            df = pd.read_sql(q, con)
            df.to_csv(EXPORTS / f"{name}.csv", index=False)
            print(f"Exported {name}.csv ({len(df):,} rows)")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--setup", action="store_true", help="create schema, seed data and functions first")
    args = p.parse_args()
    if args.setup:
        with connect() as con:
            setup(con)
    res = write_results_md()
    charts(res)
    exports()
    print("Wrote docs/RESULTS.md, docs/figures/, exports/")


if __name__ == "__main__":
    import warnings
    warnings.filterwarnings("ignore", message="pandas only supports SQLAlchemy")
    main()
